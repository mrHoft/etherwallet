import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sourceDir = path.join(root, 'public', 'icons')
const outputFile = path.join(root, 'public', 'icons.svg')

const SVG_PATTERN = /<svg\b([^>]*)>([\s\S]*?)<\/svg>\s*$/i
const ATTRIBUTE_PATTERN = /([:\w-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g

// Attributes that belong to the standalone file rather than the symbol.
const DROPPED_ATTRIBUTES = new Set(['xmlns', 'xmlns:xlink', 'version', 'width', 'height', 'id'])

function parseAttributes(source) {
  const attributes = new Map()

  for (const match of source.matchAll(ATTRIBUTE_PATTERN)) {
    attributes.set(match[1], match[2] ?? match[3] ?? '')
  }

  return attributes
}

function indent(markup, depth) {
  const padding = '  '.repeat(depth)

  return markup
    .trim()
    .split('\n')
    .map((line) => `${padding}${line.trim()}`)
    .join('\n')
}

function toSymbol(name, svg) {
  const match = svg.match(SVG_PATTERN)

  if (!match) {
    throw new Error(`Cannot read <svg> from ${name}`)
  }

  const attributes = parseAttributes(match[1])
  const viewBox = attributes.get('viewBox')

  if (!viewBox) {
    throw new Error(`Missing viewBox in ${name}`)
  }

  const id = path.basename(name, '.svg').toLowerCase()
  const inherited = [...attributes]
    .filter(([key]) => !DROPPED_ATTRIBUTES.has(key) && key !== 'viewBox')
    .map(([key, value]) => `${key}="${value}"`)

  const symbolAttributes = [`id="${id}"`, `viewBox="${viewBox}"`, ...inherited].join(' ')
  const content = match[2].replace(/<!--[\s\S]*?-->/g, '')

  return { id, markup: `  <symbol ${symbolAttributes}>\n${indent(content, 2)}\n  </symbol>` }
}

const files = (await readdir(sourceDir))
  .filter((file) => file.toLowerCase().endsWith('.svg'))
  .sort()

if (files.length === 0) {
  throw new Error(`No SVG icons found in ${sourceDir}`)
}

const symbols = []
const seen = new Set()

for (const file of files) {
  const svg = await readFile(path.join(sourceDir, file), 'utf8')
  const symbol = toSymbol(file, svg)

  if (seen.has(symbol.id)) {
    throw new Error(`Duplicate icon id "${symbol.id}" (from ${file})`)
  }

  seen.add(symbol.id)
  symbols.push(symbol.markup)
}

const spritesheet = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by scripts/build-icons.mjs from public/icons/*.svg. Do not edit by hand. -->',
  '<svg xmlns="http://www.w3.org/2000/svg">',
  ...symbols,
  '</svg>',
  '',
].join('\n')

await writeFile(outputFile, spritesheet)

console.log(`Wrote ${path.relative(root, outputFile)} with ${symbols.length} icons: ${[...seen].join(', ')}`)
